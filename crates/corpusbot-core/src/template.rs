fn generic_definition() -> WikiTemplate {
    WikiTemplate {
        id: Template::Generic,
        name: "Generic".to_owned(),
        icon: "notebook".to_owned(),
        description: "A general-purpose starting point using only base page types.".to_owned(),
        base_types: base_definitions(),
        extended_types: Vec::new(),
        schema_prompt: "Use only base page types and keep every claim attributable to a source."
            .to_owned(),
    }
}

fn research_definition() -> WikiTemplate {
    WikiTemplate {
        id: Template::Research,
        name: "Research".to_owned(),
        icon: "microscope".to_owned(),
        description: "Research notes with explicit thesis, methodology, and finding pages."
            .to_owned(),
        base_types: base_definitions(),
        extended_types: research_definitions(),
        schema_prompt:
            "Track thesis, methodology, finding, entities, concepts, and source evidence."
                .to_owned(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exposes_the_mvp_templates() {
        assert_eq!(Template::Generic.definition().extended_types().len(), 0);
        assert_eq!(Template::Research.definition().extended_types().len(), 3);
        assert!(Template::Generic.allows(PageType::Entity));
        assert!(!Template::Generic.allows(PageType::Thesis));
    }

    #[test]
    fn validates_allowed_routes() -> crate::Result<()> {
        let path = WikiPath::parse("wiki/thesis/Consensus.md")?;
        let frontmatter = crate::frontmatter::Frontmatter::new(
            PageType::Thesis,
            "Consensus",
            crate::date::IsoDate::parse("2026-09-07")?,
            crate::date::IsoDate::parse("2026-09-07")?,
            Vec::new(),
            Vec::new(),
            Vec::new(),
            Vec::new(),
        )?;
        assert!(
            Template::Research
                .definition()
                .validate_doc(&path, &frontmatter)
                .is_ok()
        );
        assert!(
            Template::Generic
                .definition()
                .validate_doc(&path, &frontmatter)
                .is_err()
        );
        Ok(())
    }
}
